// ---------- cart state ----------
let cart = {}; // { productId: quantity }

document.querySelectorAll(".add-to-cart-button").forEach(btn => {
  btn.addEventListener("click", () => addToCart(btn.dataset.productId));
});

function addToCart(productId) {
  cart[productId] = (cart[productId] || 0) + 1;
  renderCart();
}

function changeQty(productId, delta) {
  if (!cart[productId]) return;
  cart[productId] += delta;
  if (cart[productId] <= 0) delete cart[productId];
  renderCart();
}

function removeFromCart(productId) {
  delete cart[productId];
  renderCart();
}

function cartTotalPaise() {
  return Object.entries(cart).reduce((sum, [id, qty]) => {
    const product = products.find(p => p.id === id);
    return sum + product.pricePaise * qty;
  }, 0);
}



function renderCart() {
  const container = document.getElementById("cartItemsContainer");
  const entries = Object.entries(cart);

  if (entries.length === 0) {
    container.innerHTML = `<p class="cart-empty">Your cart is empty</p>`;
  } else {
    container.innerHTML = entries.map(([id, qty]) => {
      const product = products.find(p => p.id === id);
      return `
  <div class="cart-row">
    <img src="${product.image}">
    <div class="cart-row-info">
      <h3>${product.name}</h3>
      <p>₹${((product.pricePaise * qty) / 100).toFixed(2)}</p>
      <p class="delivery-info">Delivery by ${getDeliveryDate(
        product.deliveryDays
      )}</p>
      <div class="qty-control">
        <button data-action="dec" data-id="${id}">−</button>
        <span>${qty}</span>
        <button data-action="inc" data-id="${id}">+</button>
      </div>
      <button class="remove-btn" data-action="remove" data-id="${id}">Remove</button>
    </div>
  </div>`;
    }).join("");

    container.querySelectorAll("[data-action]").forEach(el => {
      const id = el.dataset.id, action = el.dataset.action;
      el.addEventListener("click", () => {
        if (action === "inc") changeQty(id, 1);
        if (action === "dec") changeQty(id, -1);
        if (action === "remove") removeFromCart(id);
      });
    });
  }

  document.getElementById("cartTotal").textContent =
    "₹" + (cartTotalPaise() / 100).toFixed(2);
  document.getElementById("cartCount").textContent =
    Object.values(cart).reduce((sum, qty) => sum + qty, 0);
  
  function cartMaxDeliveryDays() {
    const entries = Object.keys(cart);
    if (entries.length === 0) return 0;
    return Math.max(
      ...entries.map((id) => products.find((p) => p.id === id).deliveryDays)
    );
  }
  
  const footerDelivery = document.getElementById("cartDeliveryEstimate");
  if (footerDelivery) {
    footerDelivery.textContent = Object.keys(cart).length
      ? `Estimated delivery: ${getDeliveryDate(cartMaxDeliveryDays())}`
      : "";
  }
}

